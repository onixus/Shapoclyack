#!/usr/bin/env python3
"""Generate deterministic stdlib client methods from a deployment's OpenAPI JSON."""

import argparse
import json
import keyword
from pprint import pformat
from pathlib import Path


def generate(schema):
    operations = {}
    for path, methods in sorted(schema["paths"].items()):
        if not path.startswith("/api/v1/"):
            continue
        for method, operation in sorted(methods.items()):
            if method not in {
                "get",
                "post",
                "put",
                "patch",
                "delete",
                "head",
                "options",
            }:
                continue
            name = operation["operationId"]
            if (
                not name.isidentifier()
                or keyword.iskeyword(name)
                or name in operations
                or name in {"request", "__init__"}
            ):
                raise ValueError("Operation IDs must be unique Python identifiers")
            operations[name] = {
                "method": method.upper(),
                "path": path,
                "parameters": [
                    {
                        key: item[key]
                        for key in ("name", "in", "required")
                        if key in item
                    }
                    for item in operation.get("parameters", [])
                ],
                "requestBody": {
                    "content": {
                        media: {}
                        for media in (operation.get("requestBody") or {}).get(
                            "content", {}
                        )
                    }
                },
            }
    if not operations:
        raise ValueError("Schema contains no API v1 operations")
    return (
        "# Generated by scripts/generate-api-client.py; do not edit.\nOPERATIONS = "
        + pformat(operations, width=100, sort_dicts=True)
        + "\n"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("schema", type=Path)
    parser.add_argument(
        "--output", type=Path, default=Path("sdk/shapoclyack/operations.py")
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 instead of writing when the output would change",
    )
    args = parser.parse_args()
    text = generate(json.loads(args.schema.read_text()))
    if args.check:
        if not args.output.exists() or args.output.read_text() != text:
            raise SystemExit(
                f"{args.output} is out of date; regenerate it with "
                "scripts/generate-api-client.py (docs/api-versioning.md)"
            )
        return
    args.output.write_text(text)


if __name__ == "__main__":
    main()
