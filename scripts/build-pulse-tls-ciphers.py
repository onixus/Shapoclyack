#!/usr/bin/env python3
"""Build scanner/pipeline/pulse_data/tls_cipher_suites.tsv from the IANA registry.

The table maps a cipher suite code point to its IANA name, so a Pulse
enumeration row that carries only ``0xC02F`` can still be named and graded.
It sits next to ``services.tsv`` (not in ``scanner/data/``, which the PVC
enrichment shadows).

Usage: build-pulse-tls-ciphers.py tls-parameters-4.csv > scanner/pipeline/pulse_data/tls_cipher_suites.tsv
"""

from __future__ import annotations

import csv
import re
import sys
from collections.abc import Iterable

VALUE_RE = re.compile(r"^0x([0-9A-Fa-f]{2}),0x([0-9A-Fa-f]{2})$")
NAME_RE = re.compile(r"^TLS_[A-Za-z0-9_]+$")


def build(rows: Iterable[dict[str, str]]) -> list[tuple[int, str]]:
    """(code, name) for every single, named suite; skips ranges, Reserved and Unassigned."""
    out: dict[int, str] = {}
    for row in rows:
        value = VALUE_RE.match((row.get("Value") or "").strip())
        name = (row.get("Description") or "").strip()
        if not value or not NAME_RE.match(name):
            continue
        out.setdefault(int(value.group(1) + value.group(2), 16), name)
    return sorted(out.items())


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    with open(argv[1], newline="", encoding="utf-8") as fh:
        entries = build(csv.DictReader(fh))
    print("# IANA TLS Cipher Suites registry (tls-parameters-4.csv, public domain), fetched 2026-10-10.")
    print("# Source: https://www.iana.org/assignments/tls-parameters/tls-parameters.xhtml#tls-parameters-4")
    print("# Generated by scripts/build-pulse-tls-ciphers.py; do not edit by hand.")
    print("# Format: 0xCODE<TAB>IANA_NAME")
    for code, name in entries:
        print(f"0x{code:04X}\t{name}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
