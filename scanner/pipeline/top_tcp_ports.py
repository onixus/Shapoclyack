def _dedupe(ports: tuple[int, ...] | list[int]) -> tuple[int, ...]:
    seen: set[int] = set()
    out: list[int] = []
    for port in ports:
        if port in seen or not (1 <= port <= 65535):
            continue
        seen.add(port)
        out.append(port)
    return tuple(out)


