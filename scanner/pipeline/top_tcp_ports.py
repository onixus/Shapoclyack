def top_tcp_ports(n: int) -> tuple[int, ...]:
    """Return the first ``n`` ports of the curated set (100 or 1000 typical)."""
    if n <= 0:
        return ()
    if n <= 100:
        return TOP_TCP_100[:n]
    return TOP_TCP_1000[: min(n, len(TOP_TCP_1000))]
