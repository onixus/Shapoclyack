"""Version 1 local-operator exchange contracts (#584).

These schemas validate shape and evidence consistency, not authorization. Only
``AnswerPayload`` may be generated by a model. A trusted service constructs the
server context and result envelopes after checking the current principal and
source ownership; accepting an envelope from a client cannot grant authority.
"""
from __future__ import annotations

from datetime import datetime
from typing import Annotated, Literal

from pydantic import BaseModel, ConfigDict, Field, JsonValue, TypeAdapter, model_validator

Identifier = Annotated[str, Field(min_length=1, max_length=256)]
Digest = Annotated[str, Field(pattern=r"^[a-f0-9]{64}$")]
Reason = Annotated[str, Field(min_length=1, max_length=2000)]
EvidenceStatus = Literal["complete", "empty", "partial", "incomplete", "unknown", "unsupported", "stale", "failed"]


class Contract(BaseModel):
    model_config = ConfigDict(extra="forbid", strict=True, frozen=True)
    schema_version: Literal["1"] = "1"


class ServerContext(Contract):
    """Server-owned provenance; never pass model-supplied values as authority."""

    tenant_id: Identifier
    actor_id: Identifier
    request_id: Identifier
    snapshot_id: Identifier
    captured_at: datetime

    @model_validator(mode="after")
    def aware_time(self):
        if self.captured_at.utcoffset() is None:
            raise ValueError("captured_at must include a timezone")
        return self


class Citation(Contract):
    source_id: Identifier
    source_type: Literal["asset", "finding", "run", "coverage", "document", "audit"]
    source_hash: Digest
    snapshot_id: Identifier
    observed_at: datetime
    status: Literal["current", "partial", "stale"] = "current"

    @model_validator(mode="after")
    def aware_time(self):
        if self.observed_at.utcoffset() is None:
            raise ValueError("observed_at must include a timezone")
        return self


class AnswerPayload(Contract):
    """Untrusted model output. Resolve and authorize every citation on the server."""

    status: EvidenceStatus
    summary: Annotated[str, Field(min_length=1, max_length=16000)]
    citations: tuple[Citation, ...] = ()
    reason: Reason | None = None

    @model_validator(mode="after")
    def evidence_state(self):
        if self.status == "complete" and not self.citations:
            raise ValueError("complete answers require evidence")
        if self.status != "complete" and self.reason is None:
            raise ValueError("non-complete answers require a reason")
        if self.status == "complete" and any(c.status != "current" for c in self.citations):
            raise ValueError("partial or stale evidence cannot support a complete answer")
        if self.status == "empty" and self.citations:
            raise ValueError("empty answers cannot claim evidence")
        keys = [(c.source_id, c.source_hash, c.snapshot_id) for c in self.citations]
        if len(keys) != len(set(keys)):
            raise ValueError("duplicate citations")
        return self


class OperatorAnswer(Contract):
    context: ServerContext
    answer: AnswerPayload

    @model_validator(mode="after")
    def snapshot_matches(self):
        if any(c.snapshot_id != self.context.snapshot_id for c in self.answer.citations):
            raise ValueError("citations must belong to the server-selected snapshot")
        return self


class ToolResult(Contract):
    context: ServerContext
    tool_name: Identifier
    status: Literal["complete", "empty", "partial", "incomplete", "unknown", "unsupported", "stale", "denied", "failed", "cancelled"]
    data: JsonValue = None
    citations: tuple[Citation, ...] = ()
    reason: Reason | None = None

    @model_validator(mode="after")
    def result_state(self):
        if self.status != "complete" and self.reason is None:
            raise ValueError("non-complete tool results require a reason")
        if self.status in {"denied", "failed", "cancelled", "empty"} and (self.data is not None or self.citations):
            raise ValueError("non-data result cannot contain data")
        if any(c.snapshot_id != self.context.snapshot_id for c in self.citations):
            raise ValueError("tool evidence must match the server-selected snapshot")
        if self.status == "complete" and any(c.status != "current" for c in self.citations):
            raise ValueError("complete results cannot carry degraded evidence")
        return self


class ActionProposal(Contract):
    """Server-issued proposal record, not a callable model command."""

    context: ServerContext
    proposal_id: Identifier
    tool_name: Literal["scan.start", "scan.cancel", "remediation.create"]
    arguments: dict[str, JsonValue]
    arguments_hash: Digest
    expected_effect: Reason
    citations: tuple[Citation, ...]
    requires_confirmation: Literal[True] = True
    idempotency_key: Identifier
    expires_at: datetime

    @model_validator(mode="after")
    def proposal_state(self):
        if self.expires_at.utcoffset() is None or self.expires_at <= self.context.captured_at:
            raise ValueError("proposal expiry must be aware and after capture")
        if not self.citations or any(
            c.snapshot_id != self.context.snapshot_id or c.status != "current"
            for c in self.citations
        ):
            raise ValueError("proposal requires current evidence from its snapshot")
        return self


class ExecutionResult(Contract):
    """Server result after confirmation and fresh route/service authorization."""

    context: ServerContext
    proposal_id: Identifier
    arguments_hash: Digest
    idempotency_key: Identifier
    status: Literal["succeeded", "denied", "failed", "cancelled", "expired", "conflict"]
    resource_ids: tuple[Identifier, ...] = ()
    reason: Reason | None = None

    @model_validator(mode="after")
    def execution_state(self):
        if self.status != "succeeded" and self.reason is None:
            raise ValueError("unsuccessful execution requires a reason")
        if self.status != "succeeded" and self.resource_ids:
            raise ValueError("unsuccessful execution cannot claim created resources")
        return self


def contract_json_schema() -> dict:
    """JSON Schema bundle; regenerate docs/schemas/local-operator-v1.json from this."""
    return TypeAdapter(
        ServerContext | Citation | AnswerPayload | OperatorAnswer | ToolResult
        | ActionProposal | ExecutionResult
    ).json_schema()
